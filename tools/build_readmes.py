def fix_bold(text):
    """**negrita** -> <b>negrita</b> (el markdown no se procesa dentro de <p>)."""
    return re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)


def slug(text):
    """Ancla de GitHub: minusculas, sin signos, espacios a guiones."""
    out = []
    for ch in text.lower():
        if ch.isalnum():
            out.append(ch)
        elif ch in " -_":
            out.append("-")
    s = "".join(out)
    while "--" in s:
        s = s.replace("--", "-")
    return s.strip("-")


def langbar(code):
    partes = []
    for c, label, _ in LANGS:
        if c == code:
            partes.append(f"<b>{label}</b>")
        else:
            partes.append(f'<a href="{LANGS[[x[0] for x in LANGS].index(c)][2]}">{label}</a>')
    return '<p align="center">\n  ' + " | ".join(partes) + "\n</p>"


def bullets(lines):
    return "\n".join(lines)


def shots_block(shots):
    partes = []
    for nombre, pie in shots:
        partes.append(f'<p align="center">\n  <img src="assets/shots/{nombre}" width="820" alt="{pie}">\n'
                      f'  <br><sub>{pie}</sub>\n</p>')
    return "\n".join(partes)


